// Bundles each Vercel function into a single self-contained ESM file under api/.
// @vercel/node transpiles api/*.ts per-file (no bundling) and leaves ".ts" import
// specifiers verbatim — which Node's ESM loader can't resolve at runtime
// (ERR_MODULE_NOT_FOUND). Pre-bundling here sidesteps that: each deployed function
// has zero relative imports.
//
// Runs as part of `npm run build` (so Vercel regenerates them on every deploy —
// no drift) and standalone via `npm run build:api`.
import { build } from 'esbuild';

const functions = [
  { entry: 'scripts/sync/vercel-handler.ts', out: 'api/catalog-sync.js' },
  { entry: 'scripts/app-release/handler.ts', out: 'api/app-release.js' },
];

for (const { entry, out } of functions) {
  await build({
    entryPoints: [entry],
    outfile: out,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node18',
    // Available in the function's node_modules at runtime; @vercel/node is type-only here.
    // Everything else (jose included) is bundled in.
    external: ['@supabase/supabase-js', '@vercel/node'],
    banner: {
      js: `// GENERATED by scripts/build-api.mjs — do not edit. Source: ${entry}`,
    },
  });
}

-- 6. articulos.id: new ids start at 1000000 (SharePoint keeps assigning small ids in production until the cutover)
-- ============================================================================
do $$
declare
  v_seq  text := pg_get_serial_sequence('public.articulos', 'id');  -- articulos.id is `generated by default as identity`
  v_last bigint;
begin
  if v_seq is null then raise exception 'articulos.id has no sequence'; end if;
  execute format('select last_value from %s', v_seq) into v_last;
  if v_last < 1000000 then
    perform setval(v_seq, greatest(1000000, (select coalesce(max(id), 0) from public.articulos)), true);
  end if;
end $$;

-- Same shape as articulo_insert_mirror (rpc.sql) but WITHOUT an explicit id: the column default / sequence assigns it.
-- articulos is a SELECT-only catalog, so this DEFINER RPC is the only in-app path that creates an article.
create or replace function public.articulo_crear(
  p_codigo text, p_nombre text, p_precio numeric, p_corte text, p_activo boolean, p_detalle text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
begin
  insert into articulos (codigo, nombre, precio_unitario, corte, activo, detalle, updated_at)
  values (p_codigo, p_nombre, p_precio, p_corte, p_activo, p_detalle, now())

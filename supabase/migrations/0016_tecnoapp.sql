grant execute on function public.articulo_crear(text, text, numeric, text, boolean, text) to authenticated, service_role;

-- ============================================================================
-- 7. The check: what this file created, or it fails (and the migration with it)
-- ============================================================================
do $$
declare
  t      text;
  v_oid  oid;
  v_priv text;
  v_n    int;
  v_seq  text;
  v_last bigint;
begin
  foreach t in array array[
    'tipo_prendas', 'articulos_inventario', 'calendario_orden_lavado', 'segmentos_metricas', 'acceso_sin_qr',
    'permisos_menu_hotel', 'ordenes_limpieza', 'ordenes_limpieza_detalle', 'inventarios', 'habitaciones_inventariadas',
    'ordenes_lavado', 'ordenes_lavado_detalle', 'ordenes_reproceso', 'uso_metricas', 'sharepoint_archivo'
  ] loop
    v_oid := to_regclass('public.' || t);
    if v_oid is null then raise exception '%: the table is missing', t; end if;
    if not (select relrowsecurity from pg_class where oid = v_oid) then raise exception '%: RLS is not enabled', t; end if;
    if exists (select 1 from pg_policies where schemaname = 'public' and tablename = t) then
      raise exception '%: must have NO policies', t;
    end if;
    if not exists (select 1 from pg_attribute where attrelid = v_oid and attname = 'id' and attidentity = 'd') then
      raise exception '%: id must be a generated-by-default identity', t;
    end if;

    select count(*) into v_n from pg_class c, aclexplode(c.relacl) x
     where c.oid = v_oid and x.grantee in (0, 'anon'::regrole, 'authenticated'::regrole);
    if v_n <> 0 then raise exception '%: anon / authenticated / public still hold % privilege(s)', t, v_n; end if;

    -- Supabase's default privileges already give service_role ALL (incl. TRUNCATE, which the loader uses): require the
    -- four the BFF needs, extra ones are fine.
    select string_agg(x.privilege_type, ',' order by x.privilege_type) into v_priv
      from pg_class c, aclexplode(c.relacl) x where c.oid = v_oid and x.grantee = 'service_role'::regrole;
    if not (string_to_array(coalesce(v_priv, ''), ',') @> array['DELETE','INSERT','SELECT','UPDATE']) then
      raise exception '%: service_role must hold DELETE,INSERT,SELECT,UPDATE, it holds %', t, v_priv;
    end if;

    select count(*) into v_n from pg_class c, aclexplode(c.relacl) x
     where c.oid = to_regclass('public.' || t || '_id_seq') and x.grantee in (0, 'anon'::regrole, 'authenticated'::regrole);
    if v_n <> 0 then raise exception '%: anon / authenticated / public still hold the id sequence', t; end if;

    if obj_description(v_oid, 'pg_class') is null then raise exception '%: the table comment is missing', t; end if;

    -- every column of the 14 typed tables names its SharePoint column in a comment
    if t <> 'sharepoint_archivo' and exists (
         select 1 from pg_attribute a
          where a.attrelid = v_oid and a.attnum > 0 and not a.attisdropped
            and col_description(v_oid, a.attnum) is null) then
      raise exception '%: a column has no comment (SharePoint internalName)', t;
    end if;
  end loop;

  -- app_releases
  if not exists (select 1 from pg_attribute where attrelid = 'public.app_releases'::regclass and attname = 'app'
                  and attnotnull and not attisdropped) then
    raise exception 'app_releases: the app column is missing (or nullable)';
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.app_releases'::regclass and contype = 'u'
                  and conname = 'app_releases_app_version_commit_sha_key'
                  and pg_get_constraintdef(oid) = 'UNIQUE (app, version, commit_sha)') then
    raise exception 'app_releases: the unique (app, version, commit_sha) is missing';
  end if;
  if exists (select 1 from pg_constraint where conrelid = 'public.app_releases'::regclass and contype = 'u'
              and pg_get_constraintdef(oid) = 'UNIQUE (version, commit_sha)') then
    raise exception 'app_releases: the old unique (version, commit_sha) is still there';
  end if;

  -- articulos sequence
  v_seq := pg_get_serial_sequence('public.articulos', 'id');
  execute format('select last_value from %s', v_seq) into v_last;
  if v_last < 1000000 then raise exception 'articulos: the id sequence is still below 1000000 (%)', v_last; end if;

  -- articulo_crear
  v_oid := to_regprocedure('public.articulo_crear(text, text, numeric, text, boolean, text)');
  if v_oid is null then raise exception 'articulo_crear: the function is missing'; end if;
  if not (select prosecdef from pg_proc where oid = v_oid) then raise exception 'articulo_crear: must be SECURITY DEFINER'; end if;
  if has_function_privilege('anon', v_oid, 'execute') then raise exception 'articulo_crear: anon must not execute it'; end if;
  if not has_function_privilege('authenticated', v_oid, 'execute') or not has_function_privilege('service_role', v_oid, 'execute') then
    raise exception 'articulo_crear: authenticated and service_role must execute it';
  end if;
end $$;


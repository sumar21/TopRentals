-- 4. RLS on, no policies; only service_role gets access
-- ============================================================================
do $$
declare
  t text;
begin
  foreach t in array array[
    'tipo_prendas', 'articulos_inventario', 'calendario_orden_lavado', 'segmentos_metricas', 'acceso_sin_qr',
    'permisos_menu_hotel', 'ordenes_limpieza', 'ordenes_limpieza_detalle', 'inventarios', 'habitaciones_inventariadas',
    'ordenes_lavado', 'ordenes_lavado_detalle', 'ordenes_reproceso', 'uso_metricas', 'sharepoint_archivo'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    -- The schema's default privileges hand new tables (and sequences) to anon / authenticated: take them back.
    execute format('revoke all on public.%I from public, anon, authenticated', t);
    execute format('grant select, insert, update, delete on public.%I to service_role', t);
    execute format('revoke all on sequence public.%I from public, anon, authenticated', t || '_id_seq');
    execute format('grant usage, select on sequence public.%I to service_role', t || '_id_seq');
  end loop;
end $$;


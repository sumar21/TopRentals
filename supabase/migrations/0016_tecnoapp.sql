-- 0016 — Tecnoapp ("Hotel") on Supabase: 14 typed tables + the raw SharePoint archive + app_releases.app + articulos id range.
--
-- Context: the Tecnoapp (repo TopRentals-Tecnoapp) still runs on the SharePoint site "TopRentals". Its BFF is rewritten to
-- read and write these tables with the service role (server side only). Data comes from `npm run migrate:tecnoapp`
-- (scripts/migrate/src/tecnoapp.ts), which TRUNCATEs and reloads ONLY the 15 tables below and keeps the SharePoint item id
-- as `id`; afterwards it moves each identity to max(id), so rows the app creates get fresh ids.
--
-- Every table and column carries a COMMENT naming the SharePoint list / internal column it comes from: that is the contract
-- the BFF rewrite follows (SharePoint internal names are kept only here and in the migration mapper).
--
-- Types: SharePoint stores everything as text, so 'dd/MM/yyyy' texts are `date`, ISO DateTime columns are `timestamptz`,
-- quantities are `numeric`; hours ('HH:mm') stay `text`; statuses are `text` (no enums); id_univoco-like keys stay `text`;
-- `edificio` stays the building NAME as text (the app filters by it). Columns are nullable on purpose (legacy data is dirty).
--
-- Security: RLS on and NO policies, so anon / authenticated read nothing; only service_role (the BFF) reads and writes.
--
-- Also here:
--   * sharepoint_archivo: raw jsonb copy of every other list of the site that no table migrates;
--   * app_releases.app: both apps register production releases in the same table; unique becomes (app, version, commit_sha).
--     NOTE: the handler on main upserts onConflict 'version,commit_sha', which needs the OLD unique. Ship the handler change
--     (onConflict 'app,version,commit_sha' + app='toprentals') together with this migration. 0015's own self-check no longer
--     passes after this file (it expects the old columns / unique): do not re-run 0015 afterwards;
--   * articulos.id sequence moved to >= 1000000, so articles created from the app never collide with the SharePoint item ids
--     that production keeps assigning until the cutover;
--   * articulo_crear: insert an article WITHOUT an explicit id (uses that sequence). articulo_insert_mirror is untouched.
--
-- Aplicar: correr este archivo en el SQL Editor de Supabase. Additive and idempotent (safe to run more than once).

-- ============================================================================
-- 1. The 14 typed tables (generated from scripts/migrate/src/tecnoapp-mappings.ts; `npm run check` keeps them in sync)
-- ============================================================================

